@runtime_checkable
class InteractionTypeProvider(Protocol):
    """
    Protocol for objects that expose an interaction type.

    Implementations may use a property, dataclass field or ordinary attribute.
    Objects do not need to explicitly inherit from this protocol.
    """

    @property
    def interaction_type(self) -> Any:
        """Return the interaction type or category."""


@runtime_checkable
class InteractionScoreProvider(Protocol):
    """
    Protocol for objects exposing a previously calculated score.

    A specialized module may expose a local geometric score. The global
    DockAnalyzer scorer may use that value as an input but should not assume
    that it is already on the same scale as the final interaction score.
    """

    @property
    def score(self) -> Any:
        """Return a local or previously calculated score."""


@runtime_checkable
class InteractionStrengthProvider(Protocol):
    """Protocol for objects exposing an interaction-strength classification."""

    @property
    def strength(self) -> Any:
        """Return the strength label."""


@runtime_checkable
class InteractionClassificationProvider(Protocol):
    """Protocol for objects exposing a geometric or chemical classification."""

    @property
    def classification(self) -> Any:
        """Return the interaction classification."""


@runtime_checkable
class InteractionMetadataProvider(Protocol):
    """Protocol for objects exposing metadata."""

    @property
    def metadata(self) -> Any:
        """Return interaction metadata."""


@runtime_checkable
class ResidueScoreProvider(Protocol):
    """Protocol for objects associated with a receptor or ligand residue."""

    @property
    def residue(self) -> Any:
        """Return the associated residue-like object."""


@runtime_checkable
class PoseIdentifierProvider(Protocol):
    """Protocol for objects exposing a docking-pose identifier."""

    @property
    def pose_id(self) -> Any:
        """Return the pose identifier."""


