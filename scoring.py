"""
Interaction scoring, aggregation, normalization and ranking for DockAnalyzer.

This module converts molecular-interaction results generated by DockAnalyzer
into transparent and reproducible numerical scores.

Supported interaction families include:

- general atomic contacts;
- hydrogen bonds;
- hydrophobic interactions;
- pi-related interactions;
- salt bridges;
- steric clashes;
- externally defined or custom interaction types.

The module is responsible for:

1. assigning configurable weights to individual interactions;
2. incorporating interaction strength and geometric quality;
3. applying penalties, including steric-clash penalties;
4. preventing accidental double counting;
5. aggregating scores by interaction, residue and docking pose;
6. normalizing scores when requested;
7. ranking multiple docking poses;
8. generating interpretable score decompositions;
9. integrating scoring results with ``DockModel``;
10. producing serialization-safe scoring structures.

The score generated by this module is a DockAnalyzer interaction score. It is
a configurable heuristic used to compare the quality and diversity of detected
interactions. It must not be interpreted as a binding free energy, docking
affinity or thermodynamic quantity expressed in kcal/mol.

Design principles
-----------------
The scoring layer does not redetect molecular interactions and does not replace
the geometric or chemical validation performed by the specialized modules:

- :mod:`contacts`;
- :mod:`hbonds`;
- :mod:`hydrophobic`;
- :mod:`pi`;
- :mod:`saltbridge`.

Instead, it consumes their result objects, mappings or serialized
representations and converts them into standardized score components.

The implementation is designed to operate:

1. inside UCSF ChimeraX, using native molecular objects;
2. outside ChimeraX, using ordinary Python objects;
3. with synthetic objects used by the DockAnalyzer self-tests;
4. with dictionary-based data loaded from JSON or tabular exports.

Specialized interaction modules are intentionally not imported globally here.
Avoiding those imports reduces circular dependencies and allows ``scoring.py``
to work with structurally compatible third-party objects. Imports that are
strictly required for specialized adapters should be performed locally in the
corresponding functions.

Notes
-----
Positive score components represent favorable interactions.

Negative score components represent penalties, such as steric clashes or
invalid geometries.

A score of zero represents a neutral, ignored or rejected contribution,
depending on the associated metadata.

Raw and normalized scores must remain separate. Normalization must never
silently overwrite the original raw score.
"""

